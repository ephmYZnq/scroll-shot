pub fn draw_text_scaled(
    buf: &mut [u8],
    buf_width: usize,
    buf_height: usize,
    x: usize,
    y: usize,
    text: &str,
    color: [u8; 4],
    scale: usize,
) {
    let mut cur_x = x;
    let s = scale.max(1);
    for ch in text.chars() {
        let glyph = get_glyph(ch);
        for row in 0..8 {
            for sy in 0..s {
                let py = y + row * s + sy;
                if py >= buf_height {
                    continue;
                }
                let bits = glyph[row];
                for col in 0..8 {
                    if (bits & (1 << (7 - col))) != 0 {
                        for sx in 0..s {
                            let px = cur_x + col * s + sx;
                            if px >= buf_width {
                                continue;
                            }
                            let offset = (py * buf_width + px) * 4;
                            if offset + 3 < buf.len() {
                                buf[offset..offset + 4].copy_from_slice(&color);
                            }
                        }
                    }
                }
            }
        }
        cur_x += 8 * s;
    }
}

pub fn draw_outlined_text_scaled(
    buf: &mut [u8],
    buf_width: usize,
    buf_height: usize,
    x: usize,
    y: usize,
    text: &str,
    color: [u8; 4],
    scale: usize,
) {
    let shadow_color = [20, 20, 20, 255];
    if x > 0 {
        draw_text_scaled(buf, buf_width, buf_height, x - 1, y, text, shadow_color, scale);
    }
    draw_text_scaled(buf, buf_width, buf_height, x + 1, y, text, shadow_color, scale);
    if y > 0 {
        draw_text_scaled(buf, buf_width, buf_height, x, y - 1, text, shadow_color, scale);
    }
    draw_text_scaled(buf, buf_width, buf_height, x, y + 1, text, shadow_color, scale);
    draw_text_scaled(buf, buf_width, buf_height, x, y, text, color, scale);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_case_preservation_in_glyphs() {
        let upper_a = get_glyph('A');
        let lower_a = get_glyph('a');
        assert_ne!(upper_a, lower_a, "Lowercase 'a' must have a distinct glyph from uppercase 'A'");

        let upper_b = get_glyph('B');
        let lower_b = get_glyph('b');
        assert_ne!(upper_b, lower_b, "Lowercase 'b' must have a distinct glyph from uppercase 'B'");

        let upper_z = get_glyph('Z');
        let lower_z = get_glyph('z');
        assert_ne!(upper_z, lower_z, "Lowercase 'z' must have a distinct glyph from uppercase 'Z'");
    }
}
