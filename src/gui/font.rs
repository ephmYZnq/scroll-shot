#[allow(dead_code)]
pub const FONT_WIDTH: usize = 8;
#[allow(dead_code)]
pub const FONT_HEIGHT: usize = 8;

pub fn draw_text(
    buf: &mut [u8],
    buf_width: usize,
    buf_height: usize,
    x: usize,
    y: usize,
    text: &str,
    color: [u8; 4],
) {
    let mut cur_x = x;
    for ch in text.chars() {
        if let Some(adv) = crate::gui::system_font::draw_system_char(
            buf,
            buf_width,
            buf_height,
            cur_x,
            y + 12,
            ch,
            color,
        ) {
            cur_x += adv;
            continue;
        }

        let glyph = get_glyph(ch);
        for row in 0..8 {
            let py = y + row;
            if py >= buf_height {
                break;
            }
            let bits = glyph[row];
            for col in 0..8 {
                let px = cur_x + col;
                if px >= buf_width {
                    break;
                }
                if (bits & (1 << (7 - col))) != 0 {
                    let offset = (py * buf_width + px) * 4;
                    if offset + 3 < buf.len() {
                        buf[offset..offset + 4].copy_from_slice(&color);
                    }
                }
            }
        }
        cur_x += if ch.is_ascii() { 8 } else { 16 };
    }
}

